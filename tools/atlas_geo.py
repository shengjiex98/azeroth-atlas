#!/usr/bin/env python3
"""Write lore/atlas/data/geo.js: continents and where each zone sits on its continent map.

Usage: atlas_geo.py > lore/atlas/data/geo.js

Zone rectangles come from the game (tools/data/forever_maps.json, written by tools/maps_export.py from
Rosetta) when present, else from the Classic Era bounds in tools/data/ui_map_bounds.json projected into the
continent map's frame, which only approximates Forever's continents. Positions are percentages of the
continent images in lore/maps (1415 Eastern Kingdoms, 1414 Kalimdor).

Zone outlines and label anchors come from tools/data/zone_shapes.json (tools/atlas_shapes.py). Cities
have no painted outline; the app marks them at their center.
"""

import json
import sys
from pathlib import Path

DATA = json.loads((Path(__file__).parent / "data" / "ui_map_bounds.json").read_text())
MAPS = Path(__file__).parent.parent / "lore" / "maps"
CONTINENTS = {0: ("1415", "Eastern Kingdoms"), 1: ("1414", "Kalimdor")}
# UiMaps that are not zones: continents, the world, and instance-sized or city maps handled as zones anyway.
NOT_ZONES = {"947", "1414", "1415"}


def frame(bounds, cont):
    """A world-space box as [left, top, right, bottom] percentages of the continent map."""
    min_x, min_y, max_x, max_y = bounds
    c_min_x, c_min_y, c_max_x, c_max_y = cont
    w, h = c_max_y - c_min_y, c_max_x - c_min_x
    return [round((c_max_y - max_y) / w * 100, 2), round((c_max_x - max_x) / h * 100, 2),
            round((c_max_y - min_y) / w * 100, 2), round((c_max_x - min_x) / h * 100, 2)]


EXPORT = Path(__file__).parent / "data" / "forever_maps.json"
SHAPES = json.loads((Path(__file__).parent / "data" / "zone_shapes.json").read_text())


def main() -> None:
    exported = json.loads(EXPORT.read_text())["zones"] if EXPORT.exists() else {}
    out = {"continents": {}, "zones": {}}
    for map_id, (ui, name) in CONTINENTS.items():
        out["continents"][ui] = {"name": name, "image": f"maps/{ui}.jpg"}
    # Zones only Forever has appear in the export but not in the Classic bounds.
    for ui, game in exported.items():
        if ui not in DATA["maps"] and game.get("rect") and str(game.get("continent")) in out["continents"]:
            rect = [round(c * 100, 2) for c in game["rect"]]
            out["zones"][ui] = {"continent": str(game["continent"]), "rect": rect, "name": game.get("name"),
                                "center": [round((rect[0] + rect[2]) / 2, 2), round((rect[1] + rect[3]) / 2, 2)],
                                "image": f"maps/{ui}.jpg" if (MAPS / f"{ui}.jpg").exists() else None}
    for ui, bounds in DATA["maps"].items():
        map_id = DATA["mapIds"].get(ui)
        if ui in NOT_ZONES or map_id not in CONTINENTS:
            continue
        cont_ui = CONTINENTS[map_id][0]
        rect = frame(bounds, DATA["maps"][cont_ui])
        game = exported.get(ui) or {}
        if game.get("rect") and str(game.get("continent")) == cont_ui:
            rect = [round(c * 100, 2) for c in game["rect"]]
        out["zones"][ui] = {
            "continent": cont_ui,
            "rect": rect,
            "center": [round((rect[0] + rect[2]) / 2, 2), round((rect[1] + rect[3]) / 2, 2)],
            "image": f"maps/{ui}.jpg" if (MAPS / f"{ui}.jpg").exists() else None,
        }
    for ui, zone in out["zones"].items():
        zone.update(SHAPES.get(ui, {}))
    sys.stdout.write("// Generated by tools/atlas_geo.py; do not edit by hand.\n")
    sys.stdout.write("const GEO = " + json.dumps(out, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main()
